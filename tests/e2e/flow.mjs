// Percorso completo nell'app in modalità prova. Uso: node tests/e2e/flow.mjs <url> <cartella screenshot>
import { chromium } from 'playwright';
const [url, out] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' }).catch(() => chromium.launch());
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
const shot = (n) => page.screenshot({ path: `${out}/${n}.png`, fullPage: true });
await page.goto(url);
await page.getByRole('button', { name: 'Ho capito' }).click();
await page.getByRole('link', { name: '+ Nuovo cane' }).click();
await page.getByLabel('Nome').fill('Fido');
await page.getByLabel('Razza').fill('Irish Wolfhound');
await page.getByLabel('Peso attuale (kg)').fill('30');
await page.getByLabel('Fattore energetico').fill('1.6');
await shot('01-cane');
// il campo numerico ancora attivo fa scorrere la pagina al primo clic (Chromium senza schermo): si chiude prima
await page.evaluate(() => document.activeElement?.blur());
await page.getByRole('button', { name: 'Salva', exact: true }).click();
await page.getByText(/Ricette \(0\/\d+\)/).waitFor();
await shot('02-scheda');
await page.getByRole('link', { name: '+ Nuova ricetta' }).click();
await page.getByLabel('Nome della ricetta').fill('Manzo, avena e carote');
await page.getByLabel('Umida').check();
// manzo reale del catalogo di prova (beef_03): è il prodotto aggiornato dall'importazione più avanti
for (const n of ['Macinato di manzo crudo 3% grassi', '[TEST] Avena (fittizio)', '[TEST] Carote (fittizio)', 'Agnello']) await page.locator('label.pick', { hasText: n }).first().locator('input').check();
await shot('03-alimenti');
await page.getByRole('button', { name: /Analisi preliminare/ }).click();
await page.waitForSelector('text=Analisi preliminare (indicativa)');
for (const n of ['[TEST] Multinutriente', '[TEST] Olio di pesce', '[TEST] Farina d’ossa', 'Q.Diet']) await page.locator('label.pick', { hasText: n }).first().locator('input').check();
await shot('04-analisi');
await page.getByRole('button', { name: /Calcola le quantità/ }).click();
await page.waitForSelector('text=Dosi giornaliere', { timeout: 30000 });
await shot('05-risultato');
await page.getByRole('button', { name: 'Salva ricetta' }).click();
await page.waitForSelector('text=Storico');
await page.getByRole('button', { name: 'Modifica quantità' }).click();
await page.getByLabel('Quantità [TEST] Farina d’ossa (fittizio, per 1 g)').fill('0');
await shot('06-modifica');
await page.getByRole('button', { name: 'Salva come nuova versione' }).click();
await page.waitForSelector('text=v2 ·');
await shot('07-ricetta-v2');
const v2 = (await page.textContent('body')).includes('modificata dall’utente');
// ── catalogo: stati e importazione ──
await page.getByRole('link', { name: 'Catalogo' }).click();
await page.waitForSelector('text=Da completare');
await shot('08-catalogo');
await page.getByRole('button', { name: 'Importa' }).click();
// schema definitivo (dal commit e2e56fe): ID «test_» riservati, base per_100g, stato del valore obbligatorio
const H = 'product_id,nutrient_id,value_per_100g,unit,basis,source_id,status\n';
await page.getByLabel('…oppure incolla qui il contenuto').fill(H + 'beef_03,Calcio,15,mg,per_100g,analisi e2e,measured\nbeef_03,vitamina a,3,mgg,per_100g,analisi e2e,measured\n');
await page.getByRole('button', { name: 'Analizza (anteprima)' }).click();
await page.waitForSelector('text=non riconosciuta');
const disabled = await page.getByRole('button', { name: 'Conferma importazione' }).isDisabled();
await shot('09-import-errori');
await page.getByLabel('…oppure incolla qui il contenuto').fill(H + 'beef_03,Calcio,15,mg,per_100g,analisi e2e,measured\n');
await page.getByRole('button', { name: 'Analizza (anteprima)' }).click();
await page.waitForSelector('text=risulteranno');
await shot('10-import-anteprima');
await page.getByRole('button', { name: 'Conferma importazione' }).click();
await page.waitForSelector('text=Importazione completata');
await page.getByRole('link', { name: 'Cani' }).click();
await page.waitForSelector('text=ricetta da ricalcolare');
await shot('11-home-da-ricalcolare');
const stale = true;
const body = await page.textContent('body');
console.log(JSON.stringify({ disabledWithErrors: disabled, stale, errors, hasTest: body.includes('PROVA'), v2 }));
await browser.close();
